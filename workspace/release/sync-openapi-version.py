#!/usr/bin/env python3
"""Set `info.version` in the committed OpenAPI artifact (#1753).

openapi.yaml is regenerated byte-for-byte by springdoc, so release-please cannot
use a marker comment there. The release-please workflow runs this on its release
branch with the manifest version. Only the `version:` line directly under the
top-level `info:` block changes; the rest of the file is untouched.

USAGE  python3 workspace/release/sync-openapi-version.py <openapi.yaml> <X.Y.Z>
"""
import re
import sys


def main(argv):
    if len(argv) != 3:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    path, version = argv[1], argv[2]
    if not re.fullmatch(r"\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?", version):
        print(f"✗ not a SemVer version: {version!r}", file=sys.stderr)
        return 2
    with open(path) as f:
        lines = f.read().split("\n")
    in_info = False
    for i, line in enumerate(lines):
        if re.match(r"^\S", line):
            in_info = line.rstrip() == "info:"
            continue
        if in_info and re.match(r"^  version:", line):
            lines[i] = f"  version: {version}"
            with open(path, "w") as f:
                f.write("\n".join(lines))
            print(f"✓ {path} info.version = {version}")
            return 0
    print(f"✗ no info.version in {path}", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
