#!/usr/bin/env python3
"""
Generate docs/300-development/303-testing/INVENTORY.md from disk (#1511 / CU76).

Usage:
  python3 workspace/sdlc/generate-testing-inventory.py
  python3 workspace/sdlc/generate-testing-inventory.py --check   # exit 1 if stale
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "300-development" / "303-testing" / "INVENTORY.md"
E2E_TESTS = REPO / "testing" / "e2e" / "tests"
BACKEND_TEST = REPO / "backend-api" / "src" / "test"
FRONTEND_SRC = REPO / "frontend" / "src"
BRUNO = REPO / "backend-api" / "api-test"
TS_NAME = re.compile(r"^TS-(\d{4})-.+\.spec\.ts$")

MARKER_BEGIN = "<!-- TESTING-INVENTORY:BEGIN -->"
MARKER_END = "<!-- TESTING-INVENTORY:END -->"


def collect_ts_specs() -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for path in sorted(E2E_TESTS.glob("*.spec.ts")):
        match = TS_NAME.match(path.name)
        suite_id = f"TS-{match.group(1)}" if match else "(invalid)"
        rows.append((suite_id, path.name))
    return rows


def build_body() -> str:
    specs = collect_ts_specs()
    unit = len(list(BACKEND_TEST.rglob("unit/*Test.java"))) if BACKEND_TEST.is_dir() else 0
    integration = (
        len(list(BACKEND_TEST.rglob("integration/*Test.java"))) if BACKEND_TEST.is_dir() else 0
    )
    all_java = len(list(BACKEND_TEST.rglob("*Test.java"))) if BACKEND_TEST.is_dir() else 0
    vitest = (
        len(list(FRONTEND_SRC.rglob("*.test.ts")))
        + len(list(FRONTEND_SRC.rglob("*.test.tsx")))
        if FRONTEND_SRC.is_dir()
        else 0
    )
    bruno = len(list(BRUNO.rglob("*.yml"))) if BRUNO.is_dir() else 0
    generated = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# Testing inventory (generated)",
        "",
        f"> Auto-generated by `workspace/sdlc/generate-testing-inventory.py`.",
        f"> Do not edit by hand. Regenerate after adding or renaming suites.",
        f"> Generated: {generated}",
        "",
        MARKER_BEGIN,
        "",
        "## Volume summary",
        "",
        "| Suite | Count | Location |",
        "|-------|------:|----------|",
        f"| Playwright E2E specs | {len(specs)} | `testing/e2e/tests/*.spec.ts` |",
        f"| Backend `*Test.java` (all) | {all_java} | `backend-api/src/test` |",
        f"| Backend unit-path | {unit} | `.../unit/*Test.java` |",
        f"| Backend integration-path | {integration} | `.../integration/*Test.java` |",
        f"| Frontend Vitest files | {vitest} | `frontend/src/**/*.test.ts(x)` |",
        f"| Bruno YAML requests | {bruno} | `backend-api/api-test/**/*.yml` |",
        "",
        "## Playwright suites (TS-nnnn)",
        "",
        "| ID | Filename |",
        "|----|----------|",
    ]
    for suite_id, name in specs:
        lines.append(f"| `{suite_id}` | `{name}` |")
    lines.extend(
        [
            "",
            MARKER_END,
            "",
            "## How to refresh",
            "",
            "```bash",
            "python3 workspace/sdlc/generate-testing-inventory.py",
            "python3 workspace/sdlc/validate-testing-inventory.py",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if committed INVENTORY.md differs from regeneration",
    )
    args = parser.parse_args()
    body = build_body()
    if args.check:
        if not OUT.is_file():
            print(f"missing {OUT}", file=sys.stderr)
            return 1
        current = OUT.read_text(encoding="utf-8")

        def normalize(text: str) -> str:
            # Ignore the generation timestamp; everything else must match a fresh build.
            return re.sub(r"Generated:.*", "Generated: <stripped>", text)

        if normalize(current) != normalize(body):
            print("INVENTORY.md is stale — run generate-testing-inventory.py", file=sys.stderr)
            return 1
        print("INVENTORY.md is up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(collect_ts_specs())} Playwright specs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
