#!/usr/bin/env python3
"""
Generate a local / docs-build testing inventory report from disk (#1511 / #2117 / CU76).

Feature pull requests MUST NOT commit the generated report. Discovery validation
lives in validate-testing-inventory.py.

Usage:
  python3 workspace/sdlc/generate-testing-inventory.py
  python3 workspace/sdlc/generate-testing-inventory.py --output /tmp/report.md
  python3 workspace/sdlc/generate-testing-inventory.py --check   # optional local freshness
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO / "docs" / "300-development" / "303-testing" / "INVENTORY.generated.md"
E2E_TESTS = REPO / "testing" / "e2e" / "tests"
BACKEND_TEST = REPO / "backend-api" / "src" / "test"
FRONTEND_SRC = REPO / "frontend" / "src"
BRUNO = REPO / "backend-api" / "api-test"
TS_NAME = re.compile(r"^TS-(\d{4})-.+\.spec\.ts$")

MARKER_BEGIN = "<!-- TESTING-INVENTORY:BEGIN -->"
MARKER_END = "<!-- TESTING-INVENTORY:END -->"


def collect_ts_specs() -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for path in sorted(E2E_TESTS.glob("*.spec.ts")):
        match = TS_NAME.match(path.name)
        suite_id = f"TS-{match.group(1)}" if match else "(invalid)"
        rows.append((suite_id, path.name))
    return rows


def suite_counts() -> dict[str, int]:
    specs = collect_ts_specs()
    unit = len(list(BACKEND_TEST.rglob("unit/*Test.java"))) if BACKEND_TEST.is_dir() else 0
    integration = (
        len(list(BACKEND_TEST.rglob("integration/*Test.java"))) if BACKEND_TEST.is_dir() else 0
    )
    all_java = len(list(BACKEND_TEST.rglob("*Test.java"))) if BACKEND_TEST.is_dir() else 0
    vitest = (
        len(list(FRONTEND_SRC.rglob("*.test.ts")))
        + len(list(FRONTEND_SRC.rglob("*.test.tsx")))
        if FRONTEND_SRC.is_dir()
        else 0
    )
    bruno = len(list(BRUNO.rglob("*.yml"))) if BRUNO.is_dir() else 0
    return {
        "playwright": len(specs),
        "backend": all_java,
        "backend_unit": unit,
        "backend_integration": integration,
        "vitest": vitest,
        "bruno": bruno,
    }


def build_body() -> str:
    specs = collect_ts_specs()
    counts = suite_counts()
    generated = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# Testing inventory (generated)",
        "",
        f"> Auto-generated by `workspace/sdlc/generate-testing-inventory.py`.",
        f"> Do not commit this report on feature PRs (#2117). Local / docs-build only.",
        f"> Generated: {generated}",
        "",
        MARKER_BEGIN,
        "",
        "## Volume summary",
        "",
        "| Suite | Count | Location |",
        "|-------|------:|----------|",
        f"| Playwright E2E specs | {counts['playwright']} | `testing/e2e/tests/*.spec.ts` |",
        f"| Backend `*Test.java` (all) | {counts['backend']} | `backend-api/src/test` |",
        f"| Backend unit-path | {counts['backend_unit']} | `.../unit/*Test.java` |",
        f"| Backend integration-path | {counts['backend_integration']} | `.../integration/*Test.java` |",
        f"| Frontend Vitest files | {counts['vitest']} | `frontend/src/**/*.test.ts(x)` |",
        f"| Bruno YAML requests | {counts['bruno']} | `backend-api/api-test/**/*.yml` |",
        "",
        "## Playwright suites (TS-nnnn)",
        "",
        "| ID | Filename |",
        "|----|----------|",
    ]
    for suite_id, name in specs:
        lines.append(f"| `{suite_id}` | `{name}` |")
    lines.extend(
        [
            "",
            MARKER_END,
            "",
            "## How to refresh",
            "",
            "```bash",
            "python3 workspace/sdlc/generate-testing-inventory.py",
            "python3 workspace/sdlc/validate-testing-inventory.py",
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUT,
        help="path for the generated report (default: INVENTORY.generated.md)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if --output exists and differs from a fresh regeneration (local only)",
    )
    args = parser.parse_args()
    body = build_body()
    out: Path = args.output
    if not out.is_absolute():
        out = (REPO / out).resolve()

    if args.check:
        if not out.is_file():
            print(f"missing {out}", file=sys.stderr)
            return 1
        current = out.read_text(encoding="utf-8")

        def normalize(text: str) -> str:
            return re.sub(r"Generated:.*", "Generated: <stripped>", text)

        if normalize(current) != normalize(body):
            print(f"{out.name} is stale — run generate-testing-inventory.py", file=sys.stderr)
            return 1
        print(f"{out.name} is up to date")
        return 0

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")
    counts = suite_counts()
    print(
        f"wrote {out} "
        f"(Playwright {counts['playwright']}, backend {counts['backend']}, "
        f"Vitest {counts['vitest']}, Bruno {counts['bruno']})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
