#!/usr/bin/env python3
"""Gate 1 in one command: scaffold and complete an OpenSpec change (#1661, CU76).

WHY
---
The notaire-sdlc templates carry instructional HTML comments and the validator rejects any
section that is still only comments, so every change cost repeated validator round-trips and
hand-edited checkboxes. This tool writes the whole change from one JSON file; the agent still
decides the content (requirement, scenarios, design), only the ceremony goes away.

USAGE
  python3 workspace/sdlc/scaffold-openspec-change.py scaffold <spec.json>
  python3 workspace/sdlc/scaffold-openspec-change.py complete <change> --test <TestName>...

spec.json keys: name, issue, uc, branch, title, why, what, rule, rule_src, cap, cap_desc,
modules {backend-api|frontend|infra|ci|workspace: text}, docs [[path, change]], oos, spec
(delta-spec markdown), context, goals, nongoals, decisions, risks, testing, regression,
tasks [text], test (name used in the coverage table); optional: entities, endpoints, db,
config, arch, pw, deploy, migration.

`complete` ticks groups 1-8 and 9.1/9.3 and marks the tests passing. Groups 9.2 and 10-12 stay
open for the real PR, merge and deploy. Set NOTAIRE_REPO_ROOT to operate on another checkout.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(os.environ.get("NOTAIRE_REPO_ROOT") or Path(__file__).resolve().parents[2])
CHANGES = ROOT / "docs" / "openspec" / "changes"
TEMPLATES = ROOT / "docs" / "openspec" / "schemas" / "notaire-sdlc" / "templates"

MODULE_ROWS = (
    ("`backend-api`", "backend-api"),
    ("`frontend`", "frontend"),
    ("`frontend-swing`", "frontend-swing"),
    ("`infra` / observability", "infra"),
    ("CI/CD (`.github/workflows`)", "ci"),
)


def module_table(modules: dict[str, str]) -> str:
    rows = [f"| {label} | yes | {modules[key]} |" if key in modules else f"| {label} | no | — |"
            for label, key in MODULE_ROWS]
    if "workspace" in modules:
        rows.append(f"| `workspace` (harness) | yes | {modules['workspace']} |")
    return "\n".join(rows)


def proposal(c: dict) -> str:
    docs = "\n".join(f"| `{path}` | {what} |" for path, what in c["docs"])
    return f"""# {c['title']}

> Governed by [CONSTITUTION.md](../../../../CONSTITUTION.md). This proposal documents
> **only this change**; permanent documentation remains the single source of truth.

| Field | Value |
|-------|-------|
| GitHub Issue | #{c['issue']} |
| Use Case | {c['uc']} |
| Branch | `{c['branch']}` |
| Gate 1 status | passed |

## Objetivo

{c['why']}

## What Changes

{c['what']}

## Reglas de negocio

| Rule | Source | New / Changed / Made explicit |
|------|--------|-------------------------------|
| {c['rule']} | {c['rule_src']} | New |

## Capabilities

### New Capabilities

- `{c['cap']}`: {c['cap_desc']}

### Modified Capabilities

## Impact Analysis

### Módulos afectados

| Module | Touched | What changes |
|--------|---------|--------------|
{module_table(c['modules'])}

### Surface area

- Entities: {c.get('entities', 'none')}
- Endpoints: {c.get('endpoints', 'none')}
- Database (Flyway `V{{n}}`): {c.get('db', 'none')}
- Configuration / `.env`: {c.get('config', 'none')}
- Dependencies: none

### Architecture review

{c.get('arch', 'Follows the existing architecture; no ADR.')}

## Documentation Impact

| Permanent document | What must change |
|--------------------|------------------|
{docs}
| `CHANGELOG.md` | n/a — generated by release-please |

## Out of Scope

{c['oos']}
"""


def design(c: dict) -> str:
    return f"""> Governed by [CONSTITUTION.md](../../../../CONSTITUTION.md) — §6 Quality Gates.

## Context

{c['context']}

## Goals / Non-Goals

**Goals:** {c['goals']}
**Non-Goals:** {c['nongoals']}

## Decisions

{c['decisions']}

## Riesgos / Trade-offs

{c['risks']}

## Testing Strategy

{c['testing']}

## Regression Strategy

{c['regression']}

## Playwright Strategy

{c.get('pw', 'n/a — no UI surface.')}

## Deployment Strategy

{c.get('deploy', 'Ships with the next release.')}

## Rollback Strategy

Revert the PR.

## Migration Plan

{c.get('migration', 'None.')}

## Open Questions

None.
"""


def tasks(c: dict) -> str:
    text = (TEMPLATES / "tasks.md").read_text(encoding="utf-8")
    implementation = "\n".join(f"- [ ] 4.{i} {task}" for i, task in enumerate(c["tasks"], start=1))
    patched, count = re.subn(
        r"<!-- Change-specific.*?-->\n\n(?:- \[ \] 4\.\d <!-- task description -->\n?)+",
        implementation + "\n",
        text,
        flags=re.S,
    )
    if count != 1:
        raise SystemExit("tasks.md template changed: group 4 placeholder not found")
    return patched


def traceability(c: dict) -> str:
    text = (TEMPLATES / "traceability.md").read_text(encoding="utf-8")
    scenarios = re.findall(r"#### Scenario: (.*)", c["spec"])
    coverage = "\n".join(f"| {s} | {c['test']} | pending |" for s in scenarios)
    docs = "".join(f"| `{path}` | no | pending |\n" for path, _ in c["docs"])
    rows = [
        (r"\| Use Case \|[^\n]*\n", f"| Use Case | {c['uc']} | exists |\n"),
        (r"\| Specification \|[^\n]*\n", f"| Specification | `docs/openspec/changes/{c['name']}/` | passed |\n"),
        (r"\| Branch \|[^\n]*\n", f"| Branch | `{c['branch']}` | created |\n"),
        (r"\| Tasks \|[^\n]*\n", "| Tasks | `tasks.md` | in progress |\n"),
        (r"\| Commits \|[^\n]*\n", "| Commits | pending | pending |\n"),
        (r"\| Pull Request \|[^\n]*\n", "| Pull Request | pending | pending |\n"),
        (r"\| CI run \|[^\n]*\n", "| CI run | pending | pending |\n"),
        (r"\| Merge commit \|[^\n]*\n", "| Merge commit | pending | pending |\n"),
        (r"\| Release / tag \|[^\n]*\n", "| Release / tag | pending | pending |\n"),
        (r"\| Smoke test \|[^\n]*\n", "| Smoke test | pending | pending |\n"),
        (r"\| <!-- scenario name -->[^\n]*\n", coverage + "\n"),
        (r"\| <!-- path --> \|[^\n]*\n", docs),
        (r"\| 1 \| Issue \+ Specification[^\n]*\n",
         f"| 1 | Issue + Specification + Acceptance Criteria | yes | #{c['issue']}, this folder |\n"),
    ]
    for pattern, replacement in rows:
        text, count = re.subn(pattern, lambda _m, r=replacement: r, text, count=1)
        if count != 1:
            raise SystemExit(f"traceability.md template changed: {pattern}")
    text = re.sub(r"(\| [2345] \|[^|]*\|) <!-- --> \| <!-- --> \|", r"\1 pending | pending |", text)
    return re.sub(r"(## Exceptions\n\n)<!--.*?-->", r"\1None.", text, flags=re.S)


def scaffold(spec_path: Path) -> None:
    c = json.loads(spec_path.read_text(encoding="utf-8"))
    root = CHANGES / c["name"]
    (root / "specs" / c["cap"]).mkdir(parents=True, exist_ok=True)
    marker = root / ".openspec.yaml"
    if not marker.exists():
        marker.write_text(f"schema: notaire-sdlc\ncreated: {datetime.date.today().isoformat()}\n", encoding="utf-8")
    (root / "proposal.md").write_text(proposal(c), encoding="utf-8")
    (root / "design.md").write_text(design(c), encoding="utf-8")
    (root / "specs" / c["cap"] / "spec.md").write_text(c["spec"], encoding="utf-8")
    (root / "tasks.md").write_text(tasks(c), encoding="utf-8")
    (root / "traceability.md").write_text(traceability(c), encoding="utf-8")
    print(f"scaffolded {c['name']}")


TICKED_AFTER_SUITES = {(9, 1), (9, 3)}


def complete(name: str, tests: list[str]) -> None:
    root = CHANGES / name
    ticked = []
    for line in (root / "tasks.md").read_text(encoding="utf-8").split("\n"):
        match = re.match(r"- \[ \] (\d+)\.(\d+) ", line)
        if match and (int(match[1]) <= 8 or (int(match[1]), int(match[2])) in TICKED_AFTER_SUITES):
            line = line.replace("- [ ]", "- [x]", 1)
        ticked.append(line)
    (root / "tasks.md").write_text("\n".join(ticked), encoding="utf-8")
    path = root / "traceability.md"
    text = path.read_text(encoding="utf-8")
    for test in tests:
        text = text.replace(f"| {test} | pending |", f"| {test} | passing |")
    path.write_text(text, encoding="utf-8")
    print(f"completed {name}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("scaffold").add_argument("spec", type=Path)
    done = sub.add_parser("complete")
    done.add_argument("name")
    done.add_argument("--test", action="append", default=[], dest="tests")
    args = parser.parse_args(argv)
    if args.command == "scaffold":
        scaffold(args.spec)
    else:
        complete(args.name, args.tests)
    return 0


if __name__ == "__main__":
    sys.exit(main())
