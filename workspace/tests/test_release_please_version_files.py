"""#1753: every release-please cut must bump the Maven POMs and the OpenAPI info.version.

The POMs declare the Maven default namespace, so a plain `/project/version`
XPath matches nothing (0.2.1 #1597 and 0.2.2 #1718 shipped red). openapi.yaml is
regenerated byte-for-byte by springdoc, so it cannot carry a release-please
marker comment; a workflow step syncs it from the manifest instead.
"""
import json
import os
import shutil
import subprocess
import tempfile
import unittest
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SYNC = os.path.join(ROOT, "workspace", "release", "sync-openapi-version.py")
NS = "{http://maven.apache.org/POM/4.0.0}"


def extra_files():
    with open(os.path.join(ROOT, "release-please-config.json")) as f:
        return json.load(f)["packages"]["."]["extra-files"]


class PomXPathTest(unittest.TestCase):
    def xpath_for(self, path):
        entries = [e for e in extra_files() if e["path"] == path and e["type"] == "xml"]
        self.assertEqual(len(entries), 1, path)
        return entries[0]["xpath"]

    def test_pom_xpaths_are_namespace_agnostic(self):
        for path in ("pom.xml", "backend-api/pom.xml"):
            xpath = self.xpath_for(path)
            self.assertIn("local-name()", xpath, f"{path}: {xpath} cannot match a namespaced POM")

    def test_pom_xpaths_target_the_product_version_element(self):
        # Mirror each local-name() step with ElementTree to prove the element exists.
        import re
        for path, expected in (("pom.xml", "project/version"), ("backend-api/pom.xml", "project/parent/version")):
            steps = re.findall(r"local-name\(\)='([^']+)'", self.xpath_for(path))
            self.assertEqual("/".join(steps), expected, path)
            node = ET.parse(os.path.join(ROOT, path)).getroot()
            for step in steps[1:]:
                node = node.find(NS + step)
                self.assertIsNotNone(node, f"{path}: missing {step}")
            with open(os.path.join(ROOT, ".release-please-manifest.json")) as f:
                manifest = json.load(f)["."]
            self.assertEqual(node.text, manifest, path)


class OpenApiSyncTest(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.dir)
        self.spec = os.path.join(self.dir, "openapi.yaml")
        with open(self.spec, "w") as f:
            f.write("components:\n  schemas:\n    X:\n      properties:\n        version:\n"
                    "          type: string\n      type: object\ninfo:\n  title: Notaire API\n"
                    "  version: 0.2.1\nopenapi: 3.1.0\n")

    def sync(self, version):
        return subprocess.run(["python3", SYNC, self.spec, version], capture_output=True, text=True)

    def test_sets_only_info_version(self):
        self.assertEqual(self.sync("0.3.0").returncode, 0)
        text = open(self.spec).read()
        self.assertIn("info:\n  title: Notaire API\n  version: 0.3.0\n", text)
        self.assertIn("        version:\n          type: string\n", text)

    def test_idempotent(self):
        self.sync("0.3.0")
        before = open(self.spec).read()
        self.assertEqual(self.sync("0.3.0").returncode, 0)
        self.assertEqual(open(self.spec).read(), before)

    def test_rejects_non_semver(self):
        self.assertNotEqual(self.sync("latest").returncode, 0)

    def test_workflow_syncs_openapi_on_release_branch(self):
        with open(os.path.join(ROOT, ".github", "workflows", "release-please.yml")) as f:
            wf = f.read()
        self.assertIn("sync-openapi-version.py", wf)
        self.assertIn("steps.release.outputs.pr", wf)
        self.assertIn("release-please--branches--main--components--notaire", wf)


if __name__ == "__main__":
    unittest.main()
