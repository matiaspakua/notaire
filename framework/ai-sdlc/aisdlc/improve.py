"""Self-improvement loop: evidence → proposal artifact → gated PR only (#2141).

The kit never commits, never opens a forge PR, and never lets an agent approve
its own improvement. Protected-path candidates require Owner merge. Autonomy is
earned as Wilson L0 from required allowlisted-stage gates (never a fake L3) and
lost on the first incident. L1 promotion talk stays no-evaluable until ≥2 stages
each meet min_n (#2171).
"""
from __future__ import annotations

import datetime as dt
import json
import math
from collections import Counter
from pathlib import Path
from typing import Any

from aisdlc import repo
from aisdlc.context import Context
from aisdlc.evidence import LEDGER, _read

PROPOSALS_DIR = ".aisdlc/proposals"
MIN_AUTONOMY_N = 30
WILSON_FLOOR = 0.80
Z_95 = 1.96
# Allowlisted stages for Wilson (#2159/#2163/#2171). `signal` is fed by local
# preflight; `pre-push` is the second CONSTITUTION stage for multi-stage honesty
# (fixtures / future evidence feed). L1 stays no-evaluable until ≥2 qualify.
AUTONOMY_STAGES = frozenset({"signal", "pre-push"})
MIN_STAGES_FOR_L1 = 2
AGENT_APPROVERS = {"agent", "implementer", "worker", "planner", "coder", "bot"}


def wilson_lower_bound(
    successes: int,
    trials: int,
    *,
    z: float = Z_95,
    min_n: int = MIN_AUTONOMY_N,
) -> float | None:
    """Wilson score interval lower bound (default 95%). None when n < min_n."""
    if trials < min_n or trials <= 0 or successes < 0 or successes > trials:
        return None
    p = successes / trials
    z2 = z * z
    denom = 1.0 + z2 / trials
    center = p + z2 / (2.0 * trials)
    margin = z * math.sqrt((p * (1.0 - p) + z2 / (4.0 * trials)) / trials)
    return (center - margin) / denom


def _now_stamp() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def _friction_from_runs(runs: list[dict[str, Any]]) -> list[dict[str, Any]]:
    failed_gates: Counter[tuple[str, str]] = Counter()
    for run in runs:
        if run.get("ok"):
            continue
        stage = str(run.get("stage") or "unknown")
        for gate in run.get("gates") or []:
            if gate.get("status") in ("fail", "todo"):
                # skip is not fail — skip ≠ pass, but skip is not friction for a new gate
                if gate.get("status") == "todo" or gate.get("status") == "fail":
                    failed_gates[(stage, str(gate.get("name") or "?"))] += 1
    friction = []
    for (stage, gate), count in failed_gates.most_common():
        friction.append(
            {
                "stage": stage,
                "gate": gate,
                "failed_runs": count,
                "what": f"gate {gate} failed {count} time(s) in stage {stage}",
                "rule": "prefer a gate or ratchet over prose-only advice (P12)",
                "check": f"aisdlc gate {stage}",
                "suggested_paths": [
                    f".aisdlc/skills/{gate}.md",
                    "docs/300-development/",
                ],
            }
        )
    return friction


def _protected_hits(ctx: Context, paths: list[str]) -> list[str]:
    patterns = ctx.profile.protected_paths
    if not patterns:
        return []
    return [p for p in paths if repo.matches(p, patterns)]


def build_proposal(ctx: Context, since: str | None = None) -> dict[str, Any]:
    runs = _read(ctx, LEDGER, since)
    friction = _friction_from_runs(runs)
    candidates: list[str] = []
    for item in friction:
        for path in item.get("suggested_paths") or []:
            if path not in candidates:
                candidates.append(path)
    if not candidates and friction:
        candidates.append("docs/")
    protected = _protected_hits(ctx, candidates)
    merge_rule = "owner" if protected else "foreman"
    return {
        "kind": "self-improve",
        "status": "proposed",
        "commits": False,
        "approved_by": None,
        "merge_rule": merge_rule,
        "protected_owner": ctx.profile.protected_owner,
        "source": "evidence",
        "profile": ctx.profile.name,
        "runs_scanned": len(runs),
        "friction": friction,
        "candidate_paths": candidates,
        "protected_paths_touched": protected,
        "loop": [
            "1. Review proposal artifact",
            "2. Open a gated PR with candidate patches (runtime commits; agent does not)",
            "3. Pass required gates (skip ≠ pass)",
            f"4. Merge under {merge_rule} rule — never agent self-approve",
        ],
        "pr_draft": {
            "title": "chore(aisdlc): self-improve from evidence friction",
            "body": _pr_body(friction, merge_rule),
        },
    }


def _pr_body(friction: list[dict[str, Any]], merge_rule: str) -> str:
    lines = [
        "## Self-improve proposal (gated PR only)",
        "",
        "Generated by `aisdlc improve propose`. Does not commit and does not approve.",
        f"Merge rule: **{merge_rule}**.",
        "",
        "### Friction",
    ]
    if not friction:
        lines.append("- No failed-gate friction in the scanned ledger.")
    for item in friction:
        lines.append(
            f"- {item['what']} → rule: {item['rule']} → check: `{item['check']}`"
        )
    lines.extend(
        [
            "",
            "### Axioms",
            "- Agent never commits or approves.",
            "- No dual-LLM self-approval.",
            "- Ratchets unidirectional; skip ≠ pass.",
            "- Autonomy via Wilson; lost on first incident.",
        ]
    )
    return "\n".join(lines) + "\n"


def propose(ctx: Context, as_json: bool, since: str | None = None) -> int:
    proposal = build_proposal(ctx, since)
    if not proposal.get("friction"):
        # no-evaluable: skip ≠ pass, and do not write an empty proposal artifact
        empty = {
            "kind": "self-improve",
            "status": "no-evaluable",
            "commits": False,
            "approved_by": None,
            "friction": [],
            "runs_scanned": proposal.get("runs_scanned", 0),
            "detail": "no failed-gate friction in the scanned ledger",
        }
        if as_json:
            print(json.dumps(empty, indent=2, sort_keys=True))
        else:
            print(
                f"improve propose: no-evaluable — {empty['detail']} "
                f"({empty['runs_scanned']} runs scanned); no proposal written"
            )
        return 0
    out_dir = ctx.path(PROPOSALS_DIR)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"proposal-{_now_stamp()}.json"
    path.write_text(json.dumps(proposal, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    proposal["path"] = str(path)
    # rewrite with path for on-disk record
    path.write_text(json.dumps(proposal, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if as_json:
        print(json.dumps(proposal, indent=2, sort_keys=True))
    else:
        print(f"wrote proposal: {path}")
        print(f"status={proposal['status']} commits={proposal['commits']} merge_rule={proposal['merge_rule']}")
        print(f"friction items: {len(proposal['friction'])}")
        print("next: open a gated PR from the candidate paths; do not apply in place")
    return 0


def validate_proposal(ctx: Context, document: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    if document.get("kind") != "self-improve":
        errors.append("kind must be self-improve")
    status = str(document.get("status") or "")
    if status != "proposed":
        errors.append(f"status must be proposed (got {status!r}); agent cannot approve")
    if document.get("commits") is not False:
        errors.append("commits must be false — runtime owns git commit")
    approver = document.get("approved_by")
    if approver is not None:
        name = str(approver).strip().lower()
        role_names = {r.name.lower() for r in ctx.profile.roles}
        may_merge = {r.name.lower() for r in ctx.profile.roles if r.may_merge}
        if name in AGENT_APPROVERS or (name in role_names and name not in may_merge):
            errors.append(f"agent cannot approve its own improvement (approved_by={approver!r})")
        elif name:
            # any non-null approved_by on a proposal artifact is invalid — approval is merge-time
            errors.append("proposal artifacts stay unapproved; approval is the merge rule, not a field")
    merge_rule = str(document.get("merge_rule") or "")
    candidates = [str(p) for p in document.get("candidate_paths") or []]
    protected = document.get("protected_paths_touched")
    if protected is None:
        protected = _protected_hits(ctx, candidates)
    else:
        protected = [str(p) for p in protected]
    if protected and merge_rule != "owner":
        errors.append(
            f"protected paths require merge_rule=owner (touched: {', '.join(protected)}; "
            f"owner={ctx.profile.protected_owner})"
        )
    if merge_rule not in ("foreman", "owner"):
        errors.append("merge_rule must be foreman or owner")
    return errors


def validate(ctx: Context, file: Path) -> int:
    try:
        document = json.loads(file.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"improve validate: FAILED — cannot read proposal: {exc}")
        return 1
    errors = validate_proposal(ctx, document)
    if errors:
        print("improve validate: FAILED")
        for err in errors:
            print(f"  - {err}")
        return 1
    print("improve validate: PASSED — proposal is gated-PR-ready (still uncommitted)")
    return 0


def _gate_required(gate: dict[str, Any]) -> bool:
    """Missing `required` means required (matches profile default)."""
    return gate.get("required") is not False


def _allowlisted_gate_outcomes(
    runs: list[dict[str, Any]],
) -> tuple[int, int, int, bool, dict[str, int]]:
    """Count required pass/fail gates in allowlisted stages. skip/todo are not trials.

    Returns (successes, trials, failures, saw_incident_flag, trials_by_stage).
    """
    successes = 0
    failures = 0
    saw_incident = False
    trials_by_stage: dict[str, int] = {}
    for run in runs:
        stage = str(run.get("stage") or "")
        if stage not in AUTONOMY_STAGES:
            continue
        if run.get("incident") is True:
            saw_incident = True
        for gate in run.get("gates") or []:
            if not isinstance(gate, dict) or not _gate_required(gate):
                continue
            status = str(gate.get("status") or "")
            if status == "pass":
                successes += 1
                trials_by_stage[stage] = trials_by_stage.get(stage, 0) + 1
            elif status == "fail":
                failures += 1
                trials_by_stage[stage] = trials_by_stage.get(stage, 0) + 1
            # skip / todo / unknown → excluded (skip ≠ pass)
    trials = successes + failures
    return successes, trials, failures, saw_incident, trials_by_stage


def autonomy_from_runs(runs: list[dict[str, Any]], *, min_n: int = MIN_AUTONOMY_N) -> dict[str, Any]:
    """Wilson L0 grade from required allowlisted-stage gates; first incident → L1.

    Never claims L2/L3. L0-eligible detail requires ≥2 stages each with ≥ min_n
    trials (#2171); single-stage green Wilson keeps L1-not-evaluable detail.
    """
    successes, trials, failures, saw_incident, trials_by_stage = _allowlisted_gate_outcomes(runs)
    lower = wilson_lower_bound(successes, trials, min_n=min_n)
    observed = sorted(stage for stage, count in trials_by_stage.items() if count > 0)
    stages_ready = sorted(stage for stage, count in trials_by_stage.items() if count >= min_n)
    base = {
        "trials": trials,
        "successes": successes,
        "wilson_lower": lower,
        "wilson_floor": WILSON_FLOOR,
        "min_n": min_n,
        "incidents": failures,
        "stages": observed,
        "level": 0,
    }
    # Axiom 7: first incident loses autonomy → L1 (even before Wilson is evaluable).
    if failures > 0 or saw_incident:
        return {
            **base,
            "status": "demoted",
            "level": 1,
            "detail": "first incident loses autonomy",
        }
    if lower is None:
        return {**base, "status": "no-evaluable", "level": 0}
    if lower >= WILSON_FLOOR:
        if len(stages_ready) < MIN_STAGES_FOR_L1:
            return {
                **base,
                "status": "ok",
                "level": 0,
                "detail": "L1-not-evaluable (need ≥2 stages)",
            }
        return {**base, "status": "ok", "level": 0, "detail": "L0-eligible"}
    return {
        **base,
        "status": "held",
        "level": 0,
        "detail": "Wilson lower bound below floor",
    }


def autonomy(ctx: Context, as_json: bool, since: str | None = None) -> int:
    runs = _read(ctx, LEDGER, since)
    result = autonomy_from_runs(runs)
    if as_json:
        print(json.dumps(result, indent=2, sort_keys=True))
    else:
        print(
            f"autonomy: {result['status']} level={result['level']} "
            f"wilson_lower={result['wilson_lower']} "
            f"({result['successes']}/{result['trials']})"
        )
    return 0
