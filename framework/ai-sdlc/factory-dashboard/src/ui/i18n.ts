const DICTS: Record<Lang, Record<Key, string>> = { en, es };

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): Translate {
  return (key, vars) =>
    DICTS[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`));
}

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("fd.lang");
    if (saved === "en" || saved === "es") {
      return saved;
    }
  } catch {
    // storage blocked: fall back to the browser language
  }
  return navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}

export const I18n = createContext<{ t: Translate; lang: Lang }>({ t: translator("en"), lang: "en" });

export function useT(): Translate {
  return useContext(I18n).t;
}

export function useLang(): Lang {
  return useContext(I18n).lang;
}

export function hasKey(key: string): key is Key {
  return key in en;
}
